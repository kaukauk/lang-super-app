"""Word-level annotation of a subtitle line: what is it, do I know it, what does it mean.

Drives the hover-a-word overlay on the players. Three things have to be true of
every token it returns:

1. It is a word worth knowing. Particles and endings carry grammar, not vocabulary,
   so they are never highlighted — Kiwi's POS tags decide that, not a hand-kept list.
2. It is coloured by what Anki already holds. Green when the form on screen is
   literally a card, orange when the WORD is a card but not in this form — that is
   the "I know 먹다, I have never met 먹었어요" case, which is the single most useful
   thing to see while watching.
3. It glosses the way the learner's own deck glosses it, falling back to a
   translation only for words the deck has never seen.

Verbs and adjectives are shown in their 아요/어요 form rather than the dictionary
form, because that is the form the deck teaches and the form worth producing. It is
generated by Kiwi's own conjugator (`join`), so irregulars come out right — 듣다 to
들어요, 돕다 to 도와요 — without a table of exceptions here.
"""

from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Iterable, Optional

from .. import config
from ..anki.chunks import ChunkNote
from ..llm.client import LLMProvider
from . import analyzer, chunkcards, extraction, known

# What gets a highlight. Deliberately narrower than analyzer.CONTENT_TAGS: numbers
# (SN) are not vocabulary, and a learner does not need 3 glossed.
_NOUN = frozenset({"NNG", "NNP"})
_PRED = frozenset({"VV", "VA"})
_OTHER = frozenset({"MAG", "SL", "SH"})
# Verb/adjective-forming suffixes: 공부 + 하 is one word, 공부하다, not a noun that
# happens to be followed by something.
_VERBALISER = frozenset({"XSV", "XSA"})

_POS_LABEL = {"NNG": "noun", "NNP": "name", "VV": "verb", "VA": "adjective",
              "MAG": "adverb", "SL": "word", "SH": "word"}

# Anki is the source of truth but it is slow to interrogate (notesInfo over a few
# thousand notes), and a day of subtitles asks for this repeatedly.
_INDEX_TTL_S = 300.0
_MAX_GLOSS_BATCH = 40


@dataclass
class Token:
    start: int              # character span in the line — the part to highlight
    end: int
    surface: str            # exactly the characters between start and end
    word: str               # the whole whitespace word it sits in (what Anki gets)
    lemma: str              # dictionary form (predicates end in 다)
    pos: str                # noun | verb | adjective | adverb | name | word
    display: str            # 아요/어요 form for predicates, else the plain word
    gloss_en: str = ""
    status: str = "new"     # known (exact card) | derived (same word, other form) | new


@dataclass
class Line:
    text: str
    tokens: list[Token] = field(default_factory=list)


# --- what Anki knows -----------------------------------------------------

_index_cache: dict[str, Any] = {"at": 0.0, "deck": "", "value": None}


def build_index(deck: str = "Korean", *, anki=None) -> dict[str, Any]:
    """form -> gloss and lemma -> gloss, over every note the learner has studied.

    The lemma map is built ONLY from single-word notes. A note whose Korean side is
    a whole sentence would otherwise attach its gloss to every content word in it,
    and "물" would end up glossed with a sentence about water."""
    forms_to_gloss: dict[str, str] = {}
    lemma_to_gloss: dict[str, str] = {}
    for note in known.note_entries(deck, anki=anki, seen_only=True):
        gloss = note["gloss"]
        for form in note["forms"]:
            forms_to_gloss.setdefault(form, gloss)
            lemmas = analyzer.content_lemmas(form)
            if len(set(lemmas)) == 1:
                lemma_to_gloss.setdefault(lemmas[0], gloss)
    return {"forms": forms_to_gloss, "lemmas": lemma_to_gloss}


def anki_index(deck: str = "Korean", *, anki=None, refresh: bool = False,
               ) -> dict[str, Any]:
    # An explicitly supplied client is asking about THAT collection, so the cache
    # must not answer for it — silently returning some other deck's index would be
    # a very quiet way to be wrong.
    if anki is not None:
        return build_index(deck, anki=anki)
    now = time.monotonic()
    fresh = (_index_cache["value"] is not None and _index_cache["deck"] == deck
             and now - _index_cache["at"] < _INDEX_TTL_S)
    if fresh and not refresh:
        return _index_cache["value"]
    value = build_index(deck, anki=anki)
    _index_cache.update({"at": now, "deck": deck, "value": value})
    return value


def invalidate_index() -> None:
    """After a card is added, so the word it came from turns green on the next line."""
    _index_cache["value"] = None


# --- conjugation ---------------------------------------------------------

def polite_form(lemma: str, tag: str) -> str:
    """The 아요/어요 form of a dictionary form, via Kiwi's conjugator.

    Kiwi keeps the irregularity class on the tag it gave us (VV-I, VA-I), so passing
    the tag straight back through is what makes 듣다 come out as 들어요 rather than
    듣어요. A failure here is cosmetic, so it falls back to the dictionary form."""
    if not lemma.endswith("다") or len(lemma) < 2:
        return lemma
    try:
        return analyzer.conjugate_polite(lemma[:-1], tag)
    except Exception:
        return lemma


# --- tokenisation --------------------------------------------------------

def _word_spans(text: str) -> list[tuple[int, int]]:
    spans, i = [], 0
    for chunk in text.split(" "):
        if chunk:
            spans.append((i, i + len(chunk)))
        i += len(chunk) + 1
    return spans


def _word_at(spans: list[tuple[int, int]], pos: int) -> tuple[int, int]:
    for start, end in spans:
        if start <= pos < end:
            return start, end
    return pos, pos


# Sentence punctuation clings to the last word. A highlight that swallows it reads
# as though the full stop were part of the verb.
_TRAILING = '.,!?…"\'”’)]」』'


def _trim(text: str, start: int, end: int) -> int:
    while end > start and text[end - 1] in _TRAILING:
        end -= 1
    return end


def tokenize(text: str) -> list[Token]:
    """The highlightable words in one subtitle line, left to right, non-overlapping."""
    morphs = [m for m in analyzer.analyze(text) if m.start >= 0]
    spans = _word_spans(text)
    out: list[Token] = []
    i = 0
    while i < len(morphs):
        m = morphs[i]
        base = m.tag.split("-", 1)[0]
        w_start, w_end = _word_at(spans, m.start)
        w_end = _trim(text, w_start, w_end)
        nxt = morphs[i + 1] if i + 1 < len(morphs) else None

        if base in _NOUN and nxt is not None and nxt.tag in _VERBALISER \
                and nxt.start < w_end:
            # 공부 + 하 -> 공부하다: one verb, highlighted to the end of the word so
            # the conjugation the learner is looking at is inside the highlight.
            lemma = m.surface + "하다"
            end = max(w_end, m.end)
            tok = Token(start=m.start, end=end, surface=text[m.start:end],
                        word=text[w_start:end], lemma=lemma,
                        pos="verb" if nxt.tag == "XSV" else "adjective",
                        display=polite_form(lemma, "VV" if nxt.tag == "XSV" else "VA"))
            i += 2
        elif base in _PRED:
            # A predicate runs to the end of its word: the ending is not a separate
            # thing to hover, and 먹 alone highlighted out of 먹었어요 reads as a typo.
            lemma = m.lemma
            end = max(w_end, m.end)
            tok = Token(start=m.start, end=end, surface=text[m.start:end],
                        word=text[w_start:end], lemma=lemma,
                        pos=_POS_LABEL.get(base, "verb"),
                        display=polite_form(lemma, m.tag))
            i += 1
        elif base in _NOUN or base in _OTHER:
            # Just the noun: the particle after it is grammar, and the whole point of
            # the colour is that 물 is a word you know even inside 물을.
            tok = Token(start=m.start, end=m.end, surface=text[m.start:m.end],
                        word=text[w_start:w_end], lemma=m.lemma,
                        pos=_POS_LABEL.get(base, "word"), display=m.surface)
            i += 1
        else:
            i += 1
            continue

        # Kiwi can hand back overlapping spans around irregular stems; keep the
        # first, since a highlight inside another highlight cannot be rendered.
        if tok.surface.strip() and (not out or tok.start >= out[-1].end):
            out.append(tok)
    return out


# --- glossing ------------------------------------------------------------

GLOSS_SYSTEM = (
    "You gloss Korean vocabulary for an English-speaking learner watching a show.\n"
    'Return ONLY JSON: {"glosses": {"<item>": "<gloss>"}} with exactly one entry per '
    "item you were given, keyed by the item exactly as written.\n"
    "A gloss is a few words of English, no more: the meaning as used in the line "
    "given. Verbs and adjectives start with 'to ' (to eat, to be pretty). Nouns are "
    "the bare English noun. No romanisation, no notes, no markdown."
)


def _cache_path() -> Path:
    return Path(config.MEDIA_CACHE_DIR) / "gloss_cache.json"


def load_gloss_cache() -> dict[str, str]:
    p = _cache_path()
    if not p.exists():
        return {}
    try:
        data = json.loads(p.read_text("utf-8"))
    except ValueError:
        return {}
    return {k: v for k, v in data.items() if isinstance(v, str)}


def save_gloss_cache(cache: dict[str, str]) -> None:
    p = _cache_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(cache, ensure_ascii=False, sort_keys=True), encoding="utf-8")


def fetch_glosses(items: list[tuple[str, str]], *, provider: LLMProvider,
                  model: Optional[str] = None) -> dict[str, str]:
    """Gloss (lemma, example line) pairs in as few calls as possible."""
    out: dict[str, str] = {}
    for i in range(0, len(items), _MAX_GLOSS_BATCH):
        batch = items[i:i + _MAX_GLOSS_BATCH]
        user = "\n".join(f"{lemma}  (in: {line})" for lemma, line in batch)
        data = provider.complete_json(
            system=GLOSS_SYSTEM, user=user,
            model=model or config.EXTRACTION_MODEL,
            max_tokens=40 * len(batch) + 200, temperature=0.2,
        )
        glosses = (data or {}).get("glosses")
        if isinstance(glosses, dict):
            for k, v in glosses.items():
                if isinstance(v, str) and v.strip():
                    out[str(k)] = v.strip()
    return out


# --- the whole job -------------------------------------------------------

def annotate(texts: Iterable[str], *, provider: Optional[LLMProvider] = None,
             deck: str = "Korean", translate: bool = True, anki=None,
             refresh: bool = False) -> list[Line]:
    """Annotate subtitle lines: tokens, Anki status, glosses.

    Takes many lines at once on purpose. Everything expensive here is per-BATCH
    rather than per-line — one read of the deck, one LLM call for all the unknown
    words in a day — so annotating a whole episode-day costs about what one line
    would.

    Neither Anki nor the LLM being available is fatal: without Anki nothing is
    coloured, without the LLM unknown words simply have no gloss. Both still leave
    a usable overlay, which is the point — this runs while the learner is watching."""
    lines = [Line(text=t, tokens=tokenize(t)) for t in texts]

    try:
        index = anki_index(deck, anki=anki, refresh=refresh)
    except Exception:
        index = {"forms": {}, "lemmas": {}}
    forms, lemma_glosses = index["forms"], index["lemmas"]

    for line in lines:
        for tok in line.tokens:
            # Green only when what is ON SCREEN is the card. A noun without its
            # particle counts (물 inside 물을) — the particle is not part of the
            # word. A different conjugation does not: knowing 마셔요 is not the same
            # as having met 마시고, and that gap is exactly what orange is for.
            exact = [c for c in (tok.surface, tok.word) if c in forms]
            other = [c for c in (tok.display, tok.lemma) if c in forms]
            if exact:
                tok.status = "known"
                gloss = next((forms[c] for c in exact if forms[c]), "")
            elif other or tok.lemma in lemma_glosses:
                tok.status = "derived"
                gloss = next((forms[c] for c in other if forms[c]),
                             lemma_glosses.get(tok.lemma, ""))
            else:
                tok.status, gloss = "new", ""
            # A note with no English side leaves the gloss to be filled in below,
            # rather than showing a coloured word with nothing behind it.
            tok.gloss_en = gloss

    if not translate or provider is None:
        return lines

    cache = load_gloss_cache()
    wanted: dict[str, str] = {}          # lemma -> the line it appeared in
    for line in lines:
        for tok in line.tokens:
            if tok.gloss_en:
                continue
            if tok.lemma in cache:
                tok.gloss_en = cache[tok.lemma]
            else:
                wanted.setdefault(tok.lemma, line.text)

    if wanted:
        try:
            fetched = fetch_glosses(list(wanted.items()), provider=provider)
        except Exception:
            fetched = {}
        if fetched:
            cache.update(fetched)
            save_gloss_cache(cache)
        for line in lines:
            for tok in line.tokens:
                if not tok.gloss_en:
                    tok.gloss_en = cache.get(tok.lemma, "")
    return lines


# --- one clicked word into Anki ------------------------------------------

def unknown_neighbours(context_ko: str, *, start: Optional[int] = None,
                       word: str = "", deck: str = "Korean", anki=None) -> list[str]:
    """Words in the clicked word's own clause that the deck has never seen either.

    Scoped to the clause rather than the sentence because that is the unit the
    reader actually has to hold: "하지만 불의 제국이 전쟁을 일으켰고" being opaque
    does not make the clause after it unreadable."""
    lines = annotate([context_ko], translate=False, deck=deck, anki=anki)
    tokens = lines[0].tokens if lines else []
    if not tokens:
        return []
    here = next((t for t in tokens
                 if (start is not None and t.start <= start < t.end)
                 or (start is None and word and word in (t.word, t.surface))), None)
    if here is None:
        return []
    lo, hi = next(((a, b) for a, b in extraction.clause_spans(context_ko)
                   if a <= here.start < b), (0, len(context_ko)))
    return [t.surface for t in tokens
            if lo <= t.start < hi and t is not here and t.status == "new"]


def add_to_anki(*, word: str, context_ko: str, gloss_en: str = "", pos: str = "",
                display: str = "", start: Optional[int] = None, anki=None,
                tts_provider=None, deck: Optional[str] = None,
                known_deck: str = "Korean") -> dict[str, Any]:
    """Turn a clicked subtitle word into a card — a cloze when the line supports
    one, an isolated word card when it does not.

    A cloze over the line is the better card: it drills the word where it was used,
    with the sentence supplying the meaning instead of an English prompt. But that
    only works if the rest of the clause is readable. With a second unknown word in
    there the sentence stops being a cue and becomes a second thing to decode, and
    failing the card no longer tells you which word you failed on.

    So when the clause has another word the deck has never seen, the card drops the
    sentence entirely: a noun becomes Korean to English, and a verb becomes the form
    on screen to its 아요/어요 form. Narrower, but answerable — and the sentence
    version becomes worth making later, once the neighbours are known.

    For a verb the 아요/어요 form goes in as the anchor either way, so the card shows
    the derivation (먹어요 -> 먹었어요) instead of leaving the conjugation unexplained.
    """
    word, context_ko = word.strip(), context_ko.strip()
    display, gloss_en = display.strip(), gloss_en.strip()
    if not word or not context_ko:
        raise ValueError("a word and the line it came from are both required")
    predicate = pos in ("verb", "adjective")
    tags = ["korean-chunk", "lookup", "subtitle"]

    blockers = unknown_neighbours(context_ko, start=start, word=word,
                                  deck=known_deck, anki=anki)
    if blockers:
        # The word on its own. For a predicate that is the form as heard on one side
        # and the polite form on the other; for a noun, the word and its English.
        head = word if predicate else (display or word)
        note = ChunkNote(chunk_ko=head, gloss_en=gloss_en,
                         anchor=head if predicate else "",
                         target_ko=display if predicate else "",
                         tags=tags + ["isolated"])
    else:
        note = ChunkNote(chunk_ko=context_ko, blank_on=word, gloss_en=gloss_en,
                         anchor=display if predicate else "",
                         target_ko=word if predicate else "",
                         tags=tags)

    # Routed by shape rather than all into one deck: a cloze in context and a bare
    # word are different reviews, and keeping them apart lets either be tuned or
    # suspended without touching the other.
    deck = deck or (config.ANKI_MINED_WORD_DECK if blockers
                    else config.ANKI_MINED_CLOZE_DECK)
    out = chunkcards.push_notes([note], anki=anki, tts_provider=tts_provider, deck=deck)
    out["shape"] = "isolated" if blockers else "cloze"
    out["blocked_by"] = blockers
    invalidate_index()      # so the word reads as known on the very next line
    return out


def as_dicts(lines: list[Line]) -> list[dict[str, Any]]:
    return [{"text": l.text, "tokens": [asdict(t) for t in l.tokens]} for l in lines]
